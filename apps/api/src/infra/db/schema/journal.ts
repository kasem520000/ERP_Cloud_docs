import { pgTable, uuid, text, numeric, date, timestamp, integer, index, unique } from 'drizzle-orm/pg-core';
export const journalEntries = pgTable('journal_entries', {
  id: uuid('id').primaryKey(),
  tenantId: uuid('tenant_id').notNull(),
  entryNo: text('entry_no'),
  entryDate: date('entry_date').notNull(),
  fiscalPeriodId: uuid('fiscal_period_id').notNull(),
  currencyCode: text('currency_code').notNull(),
  exchangeRate: numeric('exchange_rate', { precision: 19, scale: 8 }).notNull().default('1'),
  status: text('status').notNull().default('POSTED'),
  sourceType: text('source_type').notNull(),
  sourceId: uuid('source_id'),
  operation: text('operation').notNull().default('POST'),
  reversalOfId: uuid('reversal_of_id'),
  reversedById: uuid('reversed_by_id'),
  description: text('description'),
  postedAt: timestamp('posted_at', { withTimezone: true }).notNull().defaultNow(),
  postedBy: uuid('posted_by'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  version: integer('version').notNull().default(1),
}, (t) => ({
  ixTenantDate: index('ix_journal_entries_tenant_date').on(t.tenantId, t.entryDate),
  ixSource: index('ix_journal_entries_source').on(t.tenantId, t.sourceType, t.sourceId),
  uqSourceOp: unique('uq_journal_entries_tenant_source_op').on(t.tenantId, t.sourceType, t.sourceId, t.operation),
  uqEntryNo: unique('uq_journal_entries_tenant_entry_no').on(t.tenantId, t.entryNo),
}));
export const journalLines = pgTable('journal_lines', {
  id: uuid('id').primaryKey(),
  tenantId: uuid('tenant_id').notNull(),
  journalEntryId: uuid('journal_entry_id').notNull(),
  lineNo: integer('line_no').notNull(),
  accountId: uuid('account_id').notNull(),
  direction: text('direction').notNull(),
  amount: numeric('amount', { precision: 19, scale: 4 }).notNull(),
  baseAmount: numeric('base_amount', { precision: 19, scale: 4 }).notNull(),
  partnerId: uuid('partner_id'),
  itemId: uuid('item_id'),
  costCenterId: uuid('cost_center_id'),
  taxCodeId: uuid('tax_code_id'),
  memo: text('memo'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  version: integer('version').notNull().default(1),
}, (t) => ({
  ixTenant: index('ix_journal_lines_tenant').on(t.tenantId),
  ixEntry: index('ix_journal_lines_entry').on(t.tenantId, t.journalEntryId),
  ixAccount: index('ix_journal_lines_account').on(t.tenantId, t.accountId),
}));
